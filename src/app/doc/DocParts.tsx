import type { Chapter, LayerSection, NodeRef, NodeRow, TocEntry, TowerDoc } from '../../core/doc';
import type { LinkRow } from '../../core/doc';
import { Chip } from './DocChips';
import { FieldGrid, Text } from './DocText';

export const LEVEL_NAMES: Record<1 | 2 | 3, string> = { 1: 'Images', 2: 'Overview', 3: 'Full documentation' };

/** An SVG drawing inline, not as an <img>: its text stays vector and selectable in the PDF. */
export function Svg({ markup, className }: { markup: string; className: string }) {
  return <div className={className} dangerouslySetInnerHTML={{ __html: markup }} />;
}

export const layerNumber = (index: number) => `L${String(index + 1).padStart(2, '0')}`;

/**
 * The cover: title, description, tags as chips, stat tiles, the level and the source path, and the
 * whole-tower map filling the rest of the page. The footer names the build version and the tower id,
 * never a date, so the same tower prints the same file.
 */
export function Cover({ doc, map, version }: { doc: TowerDoc; map?: string; version: string }) {
  const c = doc.generated.counts;
  const tiles: [number, string][] = [
    [c.layers, 'layers'],
    [c.nodes, 'nodes'],
    [c.agents, 'agents'],
    [c.subTowers, 'sub-towers'],
  ];
  return (
    <section className="cover">
      <p className="kicker">Flow Tower · {LEVEL_NAMES[doc.level]}</p>
      <h1>{doc.title}</h1>
      {doc.description && <p className="lead"><Text text={doc.description} /></p>}
      {doc.generated.tags.length > 0 && (
        <p className="tags">{doc.generated.tags.map((t) => <span key={t} className="chip chip-tag">{t}</span>)}</p>
      )}
      <div className="tiles">
        {tiles.map(([n, label]) => (
          <div key={label} className="tile"><strong>{n}</strong><span>{label}</span></div>
        ))}
      </div>
      <p className="meta">Level: {LEVEL_NAMES[doc.level]} · Source: <span className="mono">{doc.towerId}</span></p>
      {map && <Svg className="image map" markup={map} />}
      <p className="doc-credit">Generated by Flow Tower {version} from <span className="mono">{doc.towerId}</span></p>
    </section>
  );
}

/** Chapters as heading rows, layers under them with their code; a row links only to a printed target. */
export function Toc({ entries }: { entries: TocEntry[] }) {
  return (
    <nav className="toc" aria-label="Contents">
      <h2>Contents</h2>
      <ol>
        {entries.map((e, i) => (
          <li key={i} className={`${e.index === undefined ? 'toc-chapter' : 'toc-layer'} depth-${e.depth}`}>
            {e.index !== undefined && <span className="code mono">{layerNumber(e.index)}</span>}
            {e.anchor ? <a href={`#${e.anchor}`}>{e.label}</a> : e.label}
          </li>
        ))}
      </ol>
    </nav>
  );
}

/**
 * The node table: a row per node, type and status as chips, runtime muted. The name links to its sheet
 * only when the model kept the anchor (level 3); at level 2 there is no sheet, so it prints as text.
 */
function NodeTable({ rows, caption }: { rows: NodeRow[]; caption: string }) {
  return (
    <table className="nodes">
      <caption>{caption}</caption>
      <thead>
        <tr><th>Node</th><th>Type</th><th>Status</th><th>Runtime</th><th className="summary">Summary</th></tr>
      </thead>
      <tbody>
        {rows.map((r, i) => (
          <tr key={r.key} className={i % 2 ? 'zebra' : undefined}>
            <td className="name">{r.anchor ? <a href={`#${r.anchor}`}>{r.label}</a> : r.label}</td>
            <td><Chip kind="type" value={r.type} /></td>
            <td><Chip kind="status" value={r.status} /></td>
            <td className="muted runtime">{r.runtime ?? '—'}</td>
            <td className="summary">{r.description ? <Text text={r.description} /> : ''}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}

/**
 * One layer: heading (code, title, description) and its drawing on one landscape page; the node table
 * (levels 2-3) follows on portrait pages, captioned by the layer. Details come after.
 */
export function LayerBlock({ section, level, markup }: {
  section: LayerSection; level: 1 | 2 | 3; markup?: string;
}) {
  const code = layerNumber(section.index);
  return (
    <section className="layer">
      <div className="layer-page">
        <h3 id={section.id}><span className="code mono">{code}</span> {section.title}</h3>
        {section.description && <p className="lead"><Text text={section.description} /></p>}
        {markup && <Svg className="image layer-image" markup={markup} />}
      </div>
      {level >= 2 && section.nodes.length > 0 && (
        <NodeTable rows={section.nodes} caption={`${code} · ${section.title} — nodes`} />
      )}
    </section>
  );
}

/** A node name as a link to its detail when the document prints one, else as plain text. */
export function linkTo(ref: NodeRef) {
  return ref.anchor ? <a href={`#${ref.anchor}`}>{ref.label}</a> : ref.label;
}

export function LinkList({ links }: { links: LinkRow[] }) {
  return (
    <section className="links">
      <h3>Links</h3>
      <ul>
        {links.map((l, i) => (
          <li key={i}>
            {linkTo(l.from)} → {linkTo(l.to)}
            {' '}<span className="muted">{l.label ? <><Text text={l.label} /> · </> : null}{l.kind}</span>
          </li>
        ))}
      </ul>
    </section>
  );
}

export function ChapterHead({ chapter }: { chapter: Chapter }) {
  return (
    <header className="chapter-head">
      <h2 id={chapter.id}>{chapter.title}</h2>
      {chapter.description && <p className="lead"><Text text={chapter.description} /></p>}
      {chapter.budget && <FieldGrid fields={chapter.budget} />}
    </header>
  );
}
