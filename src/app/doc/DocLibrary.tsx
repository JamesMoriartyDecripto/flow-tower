import type { TowerDoc } from '../../core/doc';
import { Mark } from './Mark';

/**
 * The library's cover: the mark, the library name, how many projects and the totals over them. Like the
 * tower cover it carries no date, so the same projects print the same file.
 */
export function LibraryCover({ doc, version }: { doc: TowerDoc; version: string }) {
  const c = doc.generated.counts;
  const projects = doc.projects?.length ?? 0;
  const tiles: [number, string][] = [
    [projects, 'projects'],
    [c.layers, 'layers'],
    [c.nodes, 'nodes'],
    [c.agents, 'agents'],
    [c.subTowers, 'sub-towers'],
  ];
  return (
    <section className="cover">
      <header className="band corners">
        <Mark size="lg" />
        <h1>{doc.title}</h1>
        <p className="kicker">{`${projects} PROJECTS — OVERVIEW`}</p>
      </header>
      <div className="tiles">
        {tiles.map(([n, label]) => (
          <div key={label} className="tile corners"><strong>{n}</strong><span>{label}</span></div>
        ))}
      </div>
      <p className="meta">Level: Library · Projects: {(doc.projects ?? []).map((p) => p.title).join(', ')}</p>
      <p className="doc-credit">Generated by Flow Tower {version} from {projects} projects</p>
    </section>
  );
}
